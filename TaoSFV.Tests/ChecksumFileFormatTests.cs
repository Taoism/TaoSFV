using System;
using System.IO;
using System.Text;
using TaoSFV.Hash;
using TaoSFV.Model.Workset;
using Xunit;

namespace TaoSFV.Tests
{
	public class ChecksumFileFormatTests : IDisposable
	{
		private const string EmptyMD5 = "d41d8cd98f00b204e9800998ecf8427e";
		private const string EmptySHA1 = "da39a3ee5e6b4b0d3255bfef95601890afd80709";

		private readonly string _dir;

		static ChecksumFileFormatTests()
		{
			Encoding.RegisterProvider(CodePagesEncodingProvider.Instance);
		}

		public ChecksumFileFormatTests()
		{
			_dir = Path.Combine(Path.GetTempPath(), "TaoSFV.Tests", Guid.NewGuid().ToString("N"));
			Directory.CreateDirectory(_dir);
		}

		public void Dispose()
		{
			Directory.Delete(_dir, true);
		}

		private static void AssertParses(ChecksumType type, string line, string expectedName, string expectedChecksum)
		{
			string name, checksum;
			Assert.True(ChecksumFileFormat.TryParseLine(line, type, out name, out checksum), line);
			Assert.Equal(expectedName, name);
			Assert.Equal(expectedChecksum, checksum);
		}

		private static void AssertRejects(ChecksumType type, string line)
		{
			string name, checksum;
			Assert.False(ChecksumFileFormat.TryParseLine(line, type, out name, out checksum), line);
		}

		// --- SFV

		[Theory]
		[InlineData("track01.flac AF67A815", "track01.flac", "AF67A815")]
		[InlineData("name with spaces.flac AF67A815", "name with spaces.flac", "AF67A815")]
		[InlineData("track01.flac 0xAF67A815", "track01.flac", "AF67A815")]
		[InlineData("track01.flac 0XAF67A815", "track01.flac", "AF67A815")]
		[InlineData("track01.flac $AF67A815", "track01.flac", "AF67A815")]
		[InlineData("CD1/track01.flac af67a815", "CD1\\track01.flac", "af67a815")]
		public void Sfv_ParsesLines(string line, string name, string crc)
		{
			AssertParses(ChecksumType.SFV, line, name, crc);
		}

		[Theory]
		[InlineData("track01.flac")]
		[InlineData("track01.flac AF67A8")]
		[InlineData("track01.flac AF67A81500")]
		public void Sfv_RejectsMalformedLines(string line)
		{
			AssertRejects(ChecksumType.SFV, line);
		}

		// --- MD5 / SHA-1

		[Theory]
		[InlineData(EmptyMD5 + " *file.bin", "file.bin")]          // md5sum binary mode
		[InlineData(EmptyMD5 + "  file.bin", "file.bin")]          // md5sum text mode (two spaces)
		[InlineData(EmptyMD5 + " file.bin", "file.bin")]           // ilSFV without md5sum compatibility
		[InlineData(EmptyMD5 + " *dir/sub/file.bin", "dir\\sub\\file.bin")]
		[InlineData(EmptyMD5 + " *name with spaces.bin", "name with spaces.bin")]
		[InlineData("file.bin " + EmptyMD5, "file.bin")]           // name first
		[InlineData("MD5 (file.bin) = " + EmptyMD5, "file.bin")]   // BSD
		[InlineData("MD5 (name with spaces.bin) = " + EmptyMD5, "name with spaces.bin")]
		public void Md5_ParsesLines(string line, string name)
		{
			AssertParses(ChecksumType.MD5, line, name, EmptyMD5);
		}

		[Theory]
		[InlineData(EmptySHA1 + " *file.bin", "file.bin")]
		[InlineData(EmptySHA1 + "  file.bin", "file.bin")]
		[InlineData("SHA1 (file.bin) = " + EmptySHA1, "file.bin")]
		[InlineData("file.bin " + EmptySHA1, "file.bin")]
		public void Sha1_ParsesLines(string line, string name)
		{
			AssertParses(ChecksumType.SHA1, line, name, EmptySHA1);
		}

		private const string EmptySHA256 = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855";
		private const string EmptySHA512 = "cf83e1357eefb8bdf1542850d66d8007d620e4050b5715dc83f4a921d36ce9ce47d0d13c5d85f2b0ff8318d2877eec2f63b931bd47417a81a538327af927da3e";

		[Theory]
		[InlineData(EmptySHA256 + " *file.bin", "file.bin")]
		[InlineData(EmptySHA256 + "  file.bin", "file.bin")]   // sha256sum text mode
		[InlineData("SHA256 (file.bin) = " + EmptySHA256, "file.bin")] // sha256sum --tag
		[InlineData("file.bin " + EmptySHA256, "file.bin")]
		public void Sha256_ParsesLines(string line, string name)
		{
			AssertParses(ChecksumType.SHA256, line, name, EmptySHA256);
		}

		[Theory]
		[InlineData(EmptySHA512 + "  dir/file.bin", @"dir\file.bin")]
		[InlineData("SHA512 (file.bin) = " + EmptySHA512, "file.bin")]
		public void Sha512_ParsesLines(string line, string name)
		{
			AssertParses(ChecksumType.SHA512, line, name, EmptySHA512);
		}

		[Fact]
		public void Sha256_RejectsShorterDigests()
		{
			AssertRejects(ChecksumType.SHA256, EmptySHA1 + " *file.bin");
			AssertRejects(ChecksumType.SHA512, EmptySHA256 + " *file.bin");
		}

		[Theory]
		[InlineData("d41d8cd98f00b204e9800998ecf8427e")]
		[InlineData("file.bin d41d8cd98f00b204")]
		[InlineData("MD5 (file.bin) = d41d8cd9")]
		[InlineData("MD5 (x")]
		public void Md5_RejectsMalformedLines(string line)
		{
			AssertRejects(ChecksumType.MD5, line);
		}

		[Fact]
		public void Comments_DependOnFileType()
		{
			Assert.True(ChecksumFileFormat.IsComment("; generated by hkSFV", ChecksumType.SFV));
			Assert.False(ChecksumFileFormat.IsComment("#track.flac AF67A815", ChecksumType.SFV));
			Assert.True(ChecksumFileFormat.IsComment("# md5 comment", ChecksumType.MD5));
			Assert.True(ChecksumFileFormat.IsComment("# sha1 comment", ChecksumType.SHA1));
			Assert.False(ChecksumFileFormat.IsComment(EmptyMD5 + " *x", ChecksumType.MD5));
			Assert.True(ChecksumFileFormat.IsComment("# sha256 comment", ChecksumType.SHA256));
		}

		// --- writing entries

		[Fact]
		public void Md5SumStyle_UsesSlashesLfAndHashComments()
		{
			ChecksumAlgorithm sha256 = ChecksumAlgorithm.Sha256;

			Assert.Equal(EmptySHA256 + " *CD 1/track.flac", ChecksumFileFormat.FormatEntry(sha256, true, @"CD 1\track.flac", EmptySHA256));
			Assert.Equal("\n", ChecksumFileFormat.GetNewLine(sha256, true));
			Assert.Equal("# made by TaoSFV", ChecksumFileFormat.FormatComment(sha256, true, " made by TaoSFV"));
		}

		[Fact]
		public void HkSfvStyle_KeepsBackslashesCrlfAndSemicolonComments()
		{
			// SFV ignores md5sum compatibility; md5sum-style files without it keep the ilSFV layout
			Assert.Equal(@"CD 1\track.flac AF67A815", ChecksumFileFormat.FormatEntry(ChecksumAlgorithm.Sfv, true, @"CD 1\track.flac", "AF67A815"));
			Assert.Equal("\r\n", ChecksumFileFormat.GetNewLine(ChecksumAlgorithm.Sfv, true));
			Assert.Equal("; note", ChecksumFileFormat.FormatComment(ChecksumAlgorithm.Sfv, true, " note"));

			Assert.Equal(EmptyMD5 + @" CD 1\track.flac", ChecksumFileFormat.FormatEntry(ChecksumAlgorithm.Md5, false, @"CD 1\track.flac", EmptyMD5));
			Assert.Equal("\r\n", ChecksumFileFormat.GetNewLine(ChecksumAlgorithm.Md5, false));
		}

		[Theory]
		[InlineData("sfv", true)]
		[InlineData("md5", true)]
		[InlineData("md5", false)]
		[InlineData("sha512", true)]
		public void WrittenEntries_ParseBack(string extension, bool md5SumCompatibility)
		{
			ChecksumAlgorithm algorithm = ChecksumAlgorithm.FromExtension(extension);
			string digest = algorithm.Type == ChecksumType.SFV ? "AF67A815" : new string('a', algorithm.DigestLength);
			string line = ChecksumFileFormat.FormatEntry(algorithm, md5SumCompatibility, @"Disc 1\01 Intro.flac", digest);
			string comment = ChecksumFileFormat.FormatComment(algorithm, md5SumCompatibility, " header");

			string name, checksum;
			Assert.True(ChecksumFileFormat.IsComment(comment, algorithm.Type));
			Assert.True(ChecksumFileFormat.TryParseLine(line, algorithm.Type, out name, out checksum));
			Assert.Equal(@"Disc 1\01 Intro.flac", name);
			Assert.Equal(digest, checksum);
		}

		// --- junk in real-world files

		[Fact]
		public void Loader_IgnoresNulPadding()
		{
			// the exact bytes of an SFV from the wild: two good lines, then six NUL bytes
			string path = Path.Combine(_dir, "padded.sfv");
			byte[] text = Encoding.ASCII.GetBytes("; THIS PACK PASSED THROUGH METALWORLDS SITE\r\n01-nine_inch_nails_the_line_begins_to_blur-xmr.mp3 b00f4d20\r\n");
			byte[] bytes = new byte[text.Length + 6];
			text.CopyTo(bytes, 0);
			File.WriteAllBytes(path, bytes);

			ChecksumSet set = ChecksumSetLoader.Parse(path);

			Assert.Single(set.Files);
			Assert.Equal("01-nine_inch_nails_the_line_begins_to_blur-xmr.mp3", set.Files[0].FileName);
			Assert.Equal("b00f4d20", set.Files[0].OriginalChecksum);
		}

		[Fact]
		public void Loader_IgnoresCtrlZAndNulAroundLines()
		{
			string path = Path.Combine(_dir, "dos.md5");
			File.WriteAllText(path, EmptyMD5 + " *a.bin\0\0\r\n\0\0\0\r\n" + EmptyMD5 + " *b.bin\r\n\x1a");

			ChecksumSet set = ChecksumSetLoader.Parse(path);

			Assert.Equal(new[] { "a.bin", "b.bin" }, set.Files.ConvertAll(f => f.FileName));
		}

		[Fact]
		public void Loader_StillRejectsRealGarbage()
		{
			string path = Path.Combine(_dir, "bad.sfv");
			File.WriteAllText(path, "good.flac AF67A815\r\nthis is not a checksum line\r\n");

			Assert.Throws<InvalidChecksumFileException>(() => ChecksumSetLoader.Parse(path));
		}

		// --- encodings

		[Fact]
		public void Read_Utf8WithoutBom()
		{
			string path = Path.Combine(_dir, "a.sfv");
			File.WriteAllBytes(path, new UTF8Encoding(false).GetBytes("日本語の曲.flac AF67A815\r\nÄrger.flac 00000000\r\n"));

			string[] lines = ChecksumFileFormat.ReadAllLines(path);

			Assert.Equal(new[] { "日本語の曲.flac AF67A815", "Ärger.flac 00000000" }, lines);
		}

		[Fact]
		public void Read_Windows1252()
		{
			string path = Path.Combine(_dir, "a.sfv");
			File.WriteAllBytes(path, Encoding.GetEncoding(1252).GetBytes("Café – Ärger.flac AF67A815\n"));

			Assert.Equal(new[] { "Café – Ärger.flac AF67A815" }, ChecksumFileFormat.ReadAllLines(path));
		}

		[Fact]
		public void Read_ByteOrderMarks()
		{
			foreach (Encoding encoding in new Encoding[] { new UTF8Encoding(true), Encoding.Unicode, Encoding.BigEndianUnicode, Encoding.UTF32 })
			{
				string path = Path.Combine(_dir, "bom.sfv");
				File.WriteAllText(path, "Привет.flac AF67A815\r\nb.flac 00000000", encoding);

				Assert.Equal(new[] { "Привет.flac AF67A815", "b.flac 00000000" }, ChecksumFileFormat.ReadAllLines(path));
			}
		}

		[Fact]
		public void Read_SplitsAllLineEndings()
		{
			string path = Path.Combine(_dir, "a.sfv");
			File.WriteAllText(path, "a 1\r\nb 2\nc 3\rd 4");

			Assert.Equal(new[] { "a 1", "b 2", "c 3", "d 4" }, ChecksumFileFormat.ReadAllLines(path));
		}

		[Theory]
		[InlineData("plain.flac AF67A815", 1252)]
		[InlineData("Café Ärger.flac AF67A815", 1252)]
		[InlineData("日本語.flac AF67A815", 65001)]
		[InlineData("Привет.flac AF67A815", 65001)]
		public void Write_KeepsWindows1252WhenEveryCharacterFits(string text, int expectedCodePage)
		{
			Assert.Equal(expectedCodePage, ChecksumFileFormat.ChooseWriteEncoding(text).CodePage);
		}

		[Theory]
		[InlineData("Café Ärger.flac AF67A815\r\n")]
		[InlineData("日本語の曲.flac AF67A815\r\nПривет.flac 00000000\r\n")]
		public void Write_RoundTrips(string text)
		{
			string path = Path.Combine(_dir, "out.sfv");
			ChecksumFileFormat.WriteAllText(path, text);

			byte[] bytes = File.ReadAllBytes(path);
			Assert.False(bytes.Length >= 3 && bytes[0] == 0xEF && bytes[1] == 0xBB && bytes[2] == 0xBF, "no BOM expected");
			Assert.Equal(text, ChecksumFileFormat.ReadAllText(path));
		}
	}
}
